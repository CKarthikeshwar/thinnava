// Copies docs/legal/privacy.md and terms.md into the app (spec §27.4: "the same text is also shown in the app").
// Run after editing either file:  node tools/legal/sync.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const read = (f) => readFileSync(new URL(`../../docs/legal/${f}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n').trim();
const out = `// Generated by tools/legal/sync.mjs from docs/legal/*.md. Don't edit here; edit the .md files and re-run.
export const PRIVACY_MD = ${JSON.stringify(read('privacy.md'))};
export const TERMS_MD = ${JSON.stringify(read('terms.md'))};
`;
writeFileSync(new URL('../../app/src/features/legal/text.ts', import.meta.url), out);
console.log('legal text synced');
